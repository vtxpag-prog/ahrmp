export function filterFallbackOffers(
  source: Offer[],
  filters: {
    q?: string;
    categoryId?: number;
    subcategory?: string;
    neighborhood?: string;
    featuredOnly?: boolean;
    sort?: 'recent' | 'most_used';
  },
): Offer[] {
  const q = filters.q?.trim().toLowerCase() || '';
  const sub = filters.subcategory?.trim().toLowerCase() || '';
  const hood = filters.neighborhood?.trim().toLowerCase() || '';

  const filtered = source.filter((offer) => {
    if (filters.categoryId && filters.categoryId > 0 && offer.categoryId !== filters.categoryId) {
      return false;
    }
    if (sub && offer.subcategory.toLowerCase() !== sub) {
      return false;
    }
    if (filters.featuredOnly && !offer.companyIsFeatured) {
      return false;
    }
    if (hood) {
      const hay = `${offer.companyNeighborhood || ''} ${offer.companyCity || ''}`.toLowerCase();
      if (!hay.includes(hood)) return false;
    }
    if (q) {
      const hay = `${offer.title} ${offer.description} ${offer.companyName || ''}`.toLowerCase();
      if (!hay.includes(q)) return false;
    }
    return true;
  });

  if (filters.sort === 'most_used') {
    return [...filtered].sort((a, b) => (b.redemptionsCount || 0) - (a.redemptionsCount || 0));
  }
  return [...filtered].sort(
    (a, b) => Number(Boolean(b.companyIsFeatured)) - Number(Boolean(a.companyIsFeatured)),
  );
}
